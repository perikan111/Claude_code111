/**
 * ドキュメントをカテゴリー別に取得
 */
export function getDocumentsByType(type) {
    return trpgDocuments.filter(doc => doc.metadata.type === type);
}

/**
 * すべてのドキュメントテキストを取得
 */
export function getAllDocumentTexts() {
    return trpgDocuments.map(doc => doc.text);
}

/**
 * ドキュメントの総数
 */
export function getDocumentCount() {
    return trpgDocuments.length;
}
